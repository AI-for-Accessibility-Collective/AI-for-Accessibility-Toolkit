#!/usr/bin/env bash
# Authenticate the AI4A11y agent without writing to the user's gcloud config.
set -euo pipefail

usage() {
  cat <<'EOF'
Usage:
  bash scripts/setup-gcloud-agent.sh
  bash scripts/setup-gcloud-agent.sh -- COMMAND [ARG ...]

With no command, authenticate and write data/agent-gcloud/env.sh. Source that
file in your agent's shell to use the isolated gcloud configuration and Google
client-library credentials. With -- COMMAND, run the command in that environment.

The private JSON key must already be available in the sandbox. By default:
  data/agent-gcloud/credentials.json

Overrides:
  AI4A11Y_GCLOUD_KEY_FILE    Path to a securely mounted service-account JSON key
  AI4A11Y_GCLOUD_CONFIG_DIR Writable directory for this agent's gcloud config

Requires bash, python3, gcloud, and network access to Google authentication APIs.
This script authenticates the account; it does not grant IAM permissions.
EOF
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  usage
  exit 0
fi
if [[ $# -gt 0 ]]; then
  if [[ "$1" != "--" || $# -lt 2 ]]; then
    usage >&2
    exit 2
  fi
  shift
fi

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
agent_dir="$repo_root/data/agent-gcloud"
agent_project='agentic-a11y'
agent_account='ai4a11y-gcloud-agent@agentic-a11y.iam.gserviceaccount.com'
agent_key_file="${AI4A11Y_GCLOUD_KEY_FILE:-$agent_dir/credentials.json}"
agent_config_dir="${AI4A11Y_GCLOUD_CONFIG_DIR:-$agent_dir/gcloud-config}"

for dependency in python3 gcloud; do
  if ! command -v "$dependency" >/dev/null 2>&1; then
    printf 'Required command not found: %s\n' "$dependency" >&2
    exit 1
  fi
done

# Validate without ever printing the private key. Resolve overrides so the
# environment file also works after the caller changes directories.
agent_key_file="$(python3 - "$agent_key_file" "$agent_account" "$agent_project" <<'PY'
import json
import sys
from pathlib import Path

path = Path(sys.argv[1]).expanduser().resolve()
try:
    key = json.loads(path.read_text())
except (OSError, ValueError):
    sys.exit(f"Cannot read a service-account JSON key at {path}. "
             "Mount the private key in the sandbox or set AI4A11Y_GCLOUD_KEY_FILE.")
if not isinstance(key, dict) or not all((
    key.get("type") == "service_account",
    key.get("client_email") == sys.argv[2],
    key.get("project_id") == sys.argv[3],
    isinstance(key.get("private_key"), str) and bool(key["private_key"]),
)):
    sys.exit("Key does not belong to the expected AI4A11y agent service account.")
print(path)
PY
)"

umask 077
mkdir -p -- "$agent_dir" "$agent_config_dir"
chmod 700 "$agent_dir" "$agent_config_dir"
agent_config_dir="$(cd -- "$agent_config_dir" && pwd -P)"

export CLOUDSDK_CONFIG="$agent_config_dir"
export CLOUDSDK_CORE_PROJECT="$agent_project"
export CLOUDSDK_CORE_ACCOUNT="$agent_account"
export GOOGLE_APPLICATION_CREDENTIALS="$agent_key_file"
export GOOGLE_CLOUD_PROJECT="$agent_project"

# Prevent inherited credential overrides from selecting the caller's identity.
unset CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE CLOUDSDK_AUTH_ACCESS_TOKEN
unset CLOUDSDK_AUTH_ACCESS_TOKEN_FILE CLOUDSDK_AUTH_IMPERSONATE_SERVICE_ACCOUNT

gcloud auth activate-service-account "$agent_account" \
  --key-file="$agent_key_file" --project="$agent_project" --quiet
# Exercise the key against Google's token endpoint without exposing the token.
gcloud auth print-access-token --account="$agent_account" --quiet >/dev/null

agent_env_file="$agent_dir/env.sh"
agent_env_tmp="$(mktemp "$agent_dir/.env.sh.XXXXXX")"
trap 'rm -f -- "$agent_env_tmp"' EXIT
{
  printf '# Generated by scripts/setup-gcloud-agent.sh; contains paths, not key material.\n'
  printf 'export CLOUDSDK_CONFIG=%q\n' "$CLOUDSDK_CONFIG"
  printf 'export CLOUDSDK_CORE_PROJECT=%q\n' "$CLOUDSDK_CORE_PROJECT"
  printf 'export CLOUDSDK_CORE_ACCOUNT=%q\n' "$CLOUDSDK_CORE_ACCOUNT"
  printf 'export GOOGLE_APPLICATION_CREDENTIALS=%q\n' "$GOOGLE_APPLICATION_CREDENTIALS"
  printf 'export GOOGLE_CLOUD_PROJECT=%q\n' "$GOOGLE_CLOUD_PROJECT"
  printf 'unset CLOUDSDK_AUTH_CREDENTIAL_FILE_OVERRIDE CLOUDSDK_AUTH_ACCESS_TOKEN\n'
  printf 'unset CLOUDSDK_AUTH_ACCESS_TOKEN_FILE CLOUDSDK_AUTH_IMPERSONATE_SERVICE_ACCOUNT\n'
} >"$agent_env_tmp"
chmod 600 "$agent_env_tmp"
mv -f -- "$agent_env_tmp" "$agent_env_file"
trap - EXIT

printf 'Authenticated as %s (project: %s).\n' "$agent_account" "$agent_project" >&2
if [[ $# -gt 0 ]]; then
  exec "$@"
fi
printf 'Use in this shell: source %q\n' "$agent_env_file"
printf 'Or run: bash %q -- COMMAND [ARG ...]\n' "$repo_root/scripts/setup-gcloud-agent.sh"
